"""Write (or with --check, verify) the frontend's copy of the simulation metadata.

    python scripts/generate_monte_carlo_metadata.py          # regenerate
    python scripts/generate_monte_carlo_metadata.py --check  # exit 1 if the committed file is stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.dcf_model.monte_carlo_metadata import build_static_metadata  # noqa: E402

TARGET = ROOT / "frontend" / "src" / "generated" / "monte-carlo-metadata.generated.ts"


def render() -> str:
    body = json.dumps(build_static_metadata(), indent=2, ensure_ascii=False)
    return (
        "// Generated by scripts/generate_monte_carlo_metadata.py from src/dcf_model. Do not edit by hand:\n"
        "// run the script, and commit the result. tests/dcf/test_monte_carlo_metadata.py fails when it is stale.\n"
        f"export const MONTE_CARLO_STATIC_METADATA: unknown = {body};\n"
    )


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is stale; run scripts/generate_monte_carlo_metadata.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
